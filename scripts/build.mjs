// Generates data.js (loaded by index.html) and system_design_vault_merged.md
// from questions.json, the single source of truth. Run: node scripts/build.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const data = JSON.parse(readFileSync(join(root, "questions.json"), "utf8"));
const LEVELS = ["fundamental", "intermediate", "advanced"];

// validate
const errors = [];
const ids = new Set();
const cats = new Map(data.categories.map((c) => [c.id, c]));
for (const q of data.questions) {
  if (!/^[a-z0-9-]+$/.test(q.id)) errors.push(`bad id: ${q.id}`);
  if (ids.has(q.id)) errors.push(`duplicate id: ${q.id}`);
  ids.add(q.id);
  const c = cats.get(q.cat);
  if (!c) errors.push(`${q.id}: unknown category ${q.cat}`);
  else if (!c.topics.includes(q.topic)) errors.push(`${q.id}: topic "${q.topic}" not in ${q.cat}`);
  if (!LEVELS.includes(q.level)) errors.push(`${q.id}: bad level ${q.level}`);
  if (!["mine", "ref", "both"].includes(q.source)) errors.push(`${q.id}: bad source ${q.source}`);
  for (const t of q.tags) if (!data.tags.includes(t)) errors.push(`${q.id}: unknown tag ${t}`);
  if (!q.a?.length) errors.push(`${q.id}: no answer`);
}
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

writeFileSync(
  join(root, "data.js"),
  "/* Generated by scripts/build.mjs from questions.json. Do not edit by hand. */\nwindow.VAULT=" +
    JSON.stringify(data) +
    ";\n"
);

const cap = (s) => s[0].toUpperCase() + s.slice(1);
const src = { mine: "mine", ref: "ref", both: "mine + ref" };
let md = `# Staff Design Vault\n\nGenerated from questions.json. [mine] = original question; [ref] = title from a third-party list. All answer outlines written independently.\n`;
let n = 0;
for (const c of data.categories) {
  const qs = data.questions.filter((q) => q.cat === c.id);
  md += `\n## ${c.name} (${qs.length})\n`;
  for (const t of c.topics) {
    md += `\n### ${t}\n`;
    for (const q of qs.filter((x) => x.topic === t)) {
      md += `${++n}. **${q.q}** [${src[q.source]} · ${cap(q.level)} · ${q.tags.join(", ")}]\n`;
      for (const a of q.a) md += `   - ${a}\n`;
      if (q.also.length) md += `   - _Also asked as:_ ${q.also.join(" / ")}\n`;
    }
  }
}
writeFileSync(join(root, "system_design_vault_merged.md"), md);
console.log(`ok: ${data.questions.length} questions, ${data.categories.length} categories, ${data.tags.length} tags`);
